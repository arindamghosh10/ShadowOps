# target/sandbox.py — Rule Validation Layer (Phase 2)
#
# LEARNING NOTE — Layer 1 and Layer 2 of the three-layer pass/fail system
#
# This file validates the agent's response from the Docker container
# against the business rules extracted by the Code Intelligence Agent.
# This is "Layer 1 — business rule violation" and "Layer 2 — schema
# violation" from the spec. Layer 3 (LLM judge) happens inside the
# Evaluator node when these automated checks are inconclusive.
# =============================================================================

from target.docker_executor import send_to_agent


def run_against_container(endpoint: str, chaos_payload: dict,
                          domain_model: dict) -> dict:
    """
    Sends an adversarial payload to the running Docker container and
    validates the response against the domain model's business rules.

    Args:
        endpoint: container's HTTP endpoint
        chaos_payload: structured input generated by chaos_attacker_node
        domain_model: contains business_rules and output_schema for validation

    Returns:
        {
            "passed": bool,
            "output": str,
            "error": str,
            "violated_rule": str,
            "response_time_ms": int,
        }
    """
    result = send_to_agent(endpoint, chaos_payload)

    if not result["success"]:
        # Treat crashes/errors as failures worth diagnosing —
        # a well-built agent should never crash on adversarial input
        return {
            "passed": False,
            "output": "",
            "error": result["error"],
            "violated_rule": "agent_crashed_or_errored",
            "response_time_ms": result["response_time_ms"],
        }

    response_data = result["response"]
    violated_rule = _check_business_rules(response_data, domain_model)

    if violated_rule:
        return {
            "passed": False,
            "output": str(response_data),
            "error": "",
            "violated_rule": violated_rule,
            "response_time_ms": result["response_time_ms"],
        }

    return {
        "passed": True,
        "output": str(response_data),
        "error": "",
        "violated_rule": "",
        "response_time_ms": result["response_time_ms"],
    }


def _check_business_rules(response: dict, domain_model: dict) -> str:
    """
    Layer 1 — checks the response against extracted business rules using
    simple heuristics. This catches the obvious cases automatically;
    anything ambiguous falls through to the Evaluator's LLM judge layer.
    """
    rules = domain_model.get("business_rules", [])

    for rule in rules:
        rule_lower = rule.lower()

        if ("amount" in rule_lower or "discount" in rule_lower) and "positive" in rule_lower:
            amount = response.get("amount", response.get("refund_amount", None))
            if amount is not None and amount < 0:
                return f"Violated: {rule} — response amount is negative ({amount})"

        if "future" in rule_lower and "date" in rule_lower:
            if response.get("approved") and response.get("date_validated") is False:
                return f"Violated: {rule}"

        if "maximum" in rule_lower or "limit" in rule_lower:
            amount = response.get("amount", response.get("discount", None))
            if amount is not None and isinstance(amount, (int, float)) and amount > 100000:
                return f"Violated: {rule} — value exceeds reasonable bounds ({amount})"

    return ""
